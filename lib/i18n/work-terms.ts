const instrumentationPatterns: Partial<Record<WorkTermLocale, RegExp>> = {}

function getInstrumentationPattern(locale: WorkTermLocale): RegExp | null {
    if (!instrumentationPatterns[locale]) {
        const terms = Object.keys(translations.instrumentation[locale])
            .sort((left, right) => right.length - left.length)
        if (terms.length === 0) return null

        const alternatives = terms.map(term => term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')
        instrumentationPatterns[locale] = new RegExp(
            `(^|[^\\p{L}\\p{N}])(${alternatives})(s?)(?=$|[^\\p{L}\\p{N}])`,
            'giu',
        )
    }
    return instrumentationPatterns[locale] ?? null
}

/**
 * Case-insensitive lookup of a term in a dictionary. Falls back to the raw
 * value when no key matches, so unknown/odd terms are kept as-is.
 */
function matchDictionaryKey(value: string, dictionary: Record<string, string>): string {
    const trimmed = value.trim()
    const lower = trimmed.toLocaleLowerCase()
    const key = Object.keys(dictionary).find(k => k.toLocaleLowerCase() === lower)
    return key ?? value
}
function matchDictionaryCase(value: string, dictionary: Record<string, string>): string {
    const trimmed = value.trim()
    const lower = trimmed.toLocaleLowerCase()
    const key = Object.keys(dictionary).find(k => k.toLocaleLowerCase() === lower)
    return key ? dictionary[key] : value
}
export function getLocalizedWorkTerm(value: string | null | undefined, kind: WorkTermKind, locale: Locale): string {
    if (typeof value !== 'string') return ''
    let result: string
    if (locale !== 'zh' && locale !== 'fr' && locale !== 'de') {
        // English: return the value as-is, but normalize the casing of known
        // genre terms against the dictionary keys (e.g. `oratorio` -> `Oratorio`).
        if (kind === 'type') {
            const dictionary = translations.type.zh
            result = dictionary ? matchDictionaryKey(value, dictionary) : value
        } else {
            result = value
        }
    } else {
        const dictionary = translations[kind]?.[locale]
        if (!dictionary) {
            result = value
        } else {
            const exactTranslation = dictionary[value.trim()]
            if (exactTranslation) {
                result = exactTranslation
            } else if (kind !== 'instrumentation') {
                result = matchDictionaryCase(value, dictionary)
            } else {
                const pattern = getInstrumentationPattern(locale)
                if (!pattern) {
                    result = value
                } else {
                    const translationsByTerm = new Map(
                        Object.entries(dictionary).map(([term, translation]) => [term.toLocaleLowerCase(), translation]),
                    )
                    result = value.replace(pattern, (match, prefix: string, term: string, plural: string) => {
                        const translation = translationsByTerm.get(term.toLocaleLowerCase())
                        if (!translation) return match
                        return `${prefix}${translation}${locale === 'zh' ? '' : plural}`
                    })
                }
            }
        }
    }
    if (kind === 'key') {
        result = result.replace(/-?sharp/g, '♯').replace(/-?flat/g, '♭')
    }
    return result
}